"""Original soundtrack for King Crab, synthesised from scratch (no samples, no recordings).

    python audio.py --cues cues.json --out soundtrack.wav

* 0 - ~12 s   "Pass the Butter Polka": plucky pizzicato (Karplus-Strong strings),
              oom-pah bass, woodblock ticks; busier in the rapid-request section.
* ~12 s - end  "The Table": warm felt-piano (additive synthesis with inharmonic
              partials and a hammer thump) over a slow I-V6-vi-IV in F major,
              with glockenspiel twinkles under the crown sparkles.
* a soft wooden "tap" on every hand-off (times from cues.json).

All of it is composed and generated by this script and dedicated to the public
domain (CC0-1.0); see CREDITS.md.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from scipy.signal import butter, lfilter

SR = 48000
RNG = np.random.default_rng(1126)

NOTE = {n: i for i, n in enumerate(["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"])}


def hz(name: str) -> float:
    """'A4' -> 440.0, 'C#5' etc."""
    n, o = name[:-1], int(name[-1])
    return 440.0 * 2 ** ((NOTE[n] + 12 * (o - 4) - 9) / 12)


def place(buf, sig, t, gain=1.0, pan=0.0):
    i = int(t * SR)
    if i >= buf.shape[1] or i + len(sig) <= 0:
        return
    j = min(buf.shape[1], i + len(sig))
    s = sig[: j - i] * gain
    l, r = np.sqrt(0.5 * (1 - pan)), np.sqrt(0.5 * (1 + pan))
    buf[0, i:j] += s * l
    buf[1, i:j] += s * r


def pluck(f, dur=0.45, bright=0.6, decay=0.996):
    """Karplus-Strong plucked string."""
    n = int(dur * SR)
    p = max(2, int(SR / f))
    noise = RNG.uniform(-1, 1, p)
    # pre-filter the excitation for a rounder pizzicato
    for _ in range(int((1 - bright) * 4)):
        noise = 0.5 * (noise + np.roll(noise, 1))
    out = np.zeros(n)
    buf = noise.copy()
    idx = 0
    for k in range(n):
        v = buf[idx]
        out[k] = v
        nxt = buf[(idx + 1) % p]
        buf[idx] = decay * 0.5 * (v + nxt)
        idx = (idx + 1) % p
    env = np.minimum(1, np.arange(n) / (0.002 * SR))
    env *= np.exp(-np.arange(n) / SR * 3.0)
    return out * env


def woodblock(dur=0.06, f=1700):
    n = int(dur * SR)
    t = np.arange(n) / SR
    s = np.sin(2 * np.pi * f * t) * np.exp(-t * 90) + 0.3 * np.sin(2 * np.pi * f * 1.48 * t) * np.exp(-t * 120)
    return s


def piano(f, dur=2.5, vel=0.8):
    n = int(dur * SR)
    t = np.arange(n) / SR
    B = 0.00035
    s = np.zeros(n)
    for k in range(1, 11):
        fk = k * f * np.sqrt(1 + B * k * k)
        if fk > 16000:
            break
        amp = (1.0 / k ** 1.25) * (0.6 + 0.4 * vel) ** (k * 0.35)
        dec = 0.9 + 0.55 * k + f / 900
        # two slightly detuned strings per partial: the slow beating of a real unison
        s += amp * np.exp(-t * dec) * (np.sin(2 * np.pi * fk * t) + 0.6 * np.sin(2 * np.pi * fk * 1.0007 * t + 0.4))
    s += 0.25 * np.sin(2 * np.pi * f * t) * np.exp(-t * 0.6)  # long fundamental tail
    att = np.minimum(1, t / 0.004)
    thump = RNG.normal(0, 1, n) * np.exp(-t * 160) * 0.08
    b, a = butter(2, 900 / (SR / 2))
    thump = lfilter(b, a, thump)
    rel = np.clip((dur - t) / 0.25, 0, 1)
    return (s * att + thump) * rel * vel * 0.22


def glock(f, dur=1.2):
    n = int(dur * SR)
    t = np.arange(n) / SR
    s = np.sin(2 * np.pi * f * t) * np.exp(-t * 3.5) + 0.35 * np.sin(2 * np.pi * f * 2.76 * t) * np.exp(-t * 9)
    return s * np.minimum(1, t / 0.002) * 0.35


def tap(dur=0.12):
    n = int(dur * SR)
    t = np.arange(n) / SR
    noise = RNG.normal(0, 1, n) * np.exp(-t * 70)
    b, a = butter(2, [900 / (SR / 2), 3800 / (SR / 2)], btype="band")
    knock = lfilter(b, a, noise) * 0.9
    body = np.sin(2 * np.pi * 190 * t) * np.exp(-t * 45) * 0.7 + np.sin(2 * np.pi * 410 * t) * np.exp(-t * 60) * 0.3
    return (knock + body) * np.minimum(1, t / 0.0015)


def reverb(x, wet=0.22):
    """Small Schroeder room: four combs + two all-passes, per channel."""
    out = np.zeros_like(x)
    for ch in range(x.shape[0]):
        acc = np.zeros(x.shape[1])
        for d_ms, g in ((29.7, 0.80), (37.1, 0.78), (41.1, 0.76), (43.7, 0.74)):
            D = int(d_ms * SR / 1000) + ch * 13
            a = np.zeros(D + 1)
            a[0], a[D] = 1, -g
            acc += lfilter([1], a, x[ch])
        y = acc / 4
        for d_ms, g in ((5.0, 0.7), (1.7, 0.7)):
            D = int(d_ms * SR / 1000)
            b = np.zeros(D + 1)
            b[0], b[D] = -g, 1
            a = np.zeros(D + 1)
            a[0], a[D] = 1, -g
            y = lfilter(b, a, y)
        b, a = butter(1, 5000 / (SR / 2))
        out[ch] = lfilter(b, a, y)
    return x * (1 - wet) + out * wet


def polka(total, end_t, busy_from):
    """The plucky comedy cue, 132 bpm, C major."""
    buf = np.zeros((2, int(total * SR)))
    beat = 60 / 132
    chords = [("C3", "G3", ["C4", "E4", "G4"]), ("F2", "C3", ["F4", "A4", "C5"]),
              ("G2", "D3", ["G4", "B4", "D5"]), ("C3", "G3", ["C4", "E4", "G4"])]
    tune = ["E5", "G5", "E5", "C5", "D5", "F5", "A5", "F5", "G5", "B4", "D5", "G5", "E5", "C5", "G4", "C5"]
    fast = ["E5", "G5", "C6", "G5", "F5", "A5", "C6", "A5", "D5", "G5", "B5", "G5", "C6", "G5", "E5", "C5"]
    t, bar = 0.3, 0
    while t < end_t:
        bass, fifth, triad = chords[bar % 4]
        for b4 in range(4):
            tb = t + b4 * beat
            if tb >= end_t:
                break
            if b4 % 2 == 0:
                place(buf, pluck(hz(bass), 0.5, 0.4, 0.995), tb, 0.55)
            else:
                place(buf, pluck(hz(fifth), 0.4, 0.4, 0.994), tb, 0.38)
                for k, nn in enumerate(triad):
                    place(buf, pluck(hz(nn), 0.25, 0.7, 0.990), tb + 0.004 * k, 0.12, pan=-0.3 + 0.3 * k)
            place(buf, woodblock(), tb + beat / 2, 0.10, pan=0.4)
            busy = tb >= busy_from
            line = fast if busy else tune
            note = line[(bar * 4 + b4) % 16]
            place(buf, pluck(hz(note), 0.3, 0.85, 0.992), tb, 0.30 if not busy else 0.26, pan=0.15)
            if busy:  # double-time on the rapid requests
                n2 = line[(bar * 4 + b4 + 5) % 16]
                place(buf, pluck(hz(n2), 0.22, 0.9, 0.990), tb + beat / 2, 0.18, pan=-0.15)
        t += 4 * beat
        bar += 1
    # a little "plink" sting at the end of the cue
    place(buf, pluck(hz("C6"), 0.6, 0.9, 0.995), end_t - 0.05, 0.25)
    return buf


def warm_piano(total, start, sparkle_t, final_t):
    buf = np.zeros((2, int(total * SR)))
    beat = 60 / 72
    prog = [("F2", ["F3", "A3", "C4"], "A4"), ("E2", ["C3", "G3", "C4"], "G4"),
            ("D2", ["D3", "F3", "A3"], "F4"), ("A#1", ["A#2", "F3", "D4"], "D4"),
            ("F2", ["F3", "A3", "C4"], "C5"), ("C2", ["C3", "E3", "G3"], "A#4"),
            ("A#1", ["A#2", "D3", "F3"], "A4"), ("F2", ["F3", "A3", "C4"], "F4")]
    melody = {0: ["C5", "A4"], 1: ["G4", "C5"], 2: ["A4", "F4"], 3: ["F4", "D4"],
              4: ["C5", "D5"], 5: ["E5", "C5"], 6: ["D5", "A4"], 7: ["F4"]}
    t = start
    i = 0
    while t < final_t - 0.5 and i < len(prog):
        root, chord, top = prog[i]
        span = 2 * beat
        place(buf, piano(hz(root), 3.2, 0.7), t, 1.0, pan=-0.2)
        arp = chord + [chord[1]]
        for k, nn in enumerate(arp):
            place(buf, piano(hz(nn), 2.4, 0.5), t + k * beat / 2, 0.8, pan=-0.1 + 0.07 * k)
        for k, nn in enumerate(melody.get(i, [])):
            place(buf, piano(hz(nn), 2.6, 0.75), t + k * beat, 0.95, pan=0.15)
        t += span
        i += 1
    # resolution on the final card: a rolled F major chord
    for k, nn in enumerate(["F2", "C3", "F3", "A3", "C4", "F4", "A4"]):
        place(buf, piano(hz(nn), 4.5, 0.65), final_t + 0.035 * k, 0.9, pan=-0.3 + 0.1 * k)
    # glockenspiel twinkles under the crown sparkles (F major pentatonic)
    pent = ["F5", "G5", "A5", "C6", "D6", "F6", "A6"]
    for k in range(14):
        tt = sparkle_t + k * 0.19 + RNG.uniform(-0.03, 0.03)
        place(buf, glock(hz(pent[(k * 3) % len(pent)])), tt, 0.35, pan=RNG.uniform(-0.6, 0.6))
    return buf


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cues", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    cues = json.loads(a.cues.read_text())
    total = cues["duration"]
    xfade = cues["turn"]  # the crossfade point (~12 s)
    pol = polka(total, xfade + 1.2, cues["rapid"])
    pia = warm_piano(total, xfade - 0.6, cues["sparkle"], cues["final_chord"])
    t = np.arange(int(total * SR)) / SR
    fade_out = np.clip((xfade + 1.0 - t) / 1.6, 0, 1)
    fade_in = np.clip((t - (xfade - 0.6)) / 1.4, 0, 1)
    music = reverb(pol * fade_out * 2.4) + reverb(pia * fade_in * 0.75, wet=0.32)
    # gentle soft-clip so the plucks' transients don't decide the level
    music = np.tanh(music * 1.6) / 1.6
    sfx = np.zeros_like(music)
    for tt in cues["taps"]:
        place(sfx, tap(), tt, 0.45)
    mix = music + sfx
    end = np.clip((total - t) / 0.6, 0, 1)
    mix *= end
    mix /= np.max(np.abs(mix)) + 1e-9
    mix *= 10 ** (-1.5 / 20)
    pcm = (mix.T * 32767).astype(np.int16)
    import wave
    with wave.open(str(a.out), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    print("wrote", a.out, f"{total:.2f} s")


if __name__ == "__main__":
    main()
