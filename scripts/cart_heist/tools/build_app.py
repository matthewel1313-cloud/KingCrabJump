"""Build `cart_heist.app`: the shipped Jumper bundle, trimmed to the modes Cart Heist uses.

Run with the jumper venv active:

    python build_app.py --jumper /path/to/jumper --out ../../apps/cart_heist.app

No policy is retrained and no controller is rebuilt. The `.app` keeps, byte for
byte, the compiled controller (every host's build), the ONNX/RKNN policies and
contracts of the six modes the story uses --

    locomotion       walk / crab-walk sideways / turn          (jumper.posture)
    claw_left        five legs + carried left claw: the grasp  (jumper.five_foot)
    gesture_bow      the bow                                   (jumper.gesture_bow)
    gesture_hello    the wave                                  (jumper.gesture_hello)
    gesture_salute   the salute                                (jumper.gesture_salute)
    dance_brazilian  the samba                                 (jumper.dance_brazilian)

-- and drops the rest (jump, claw_right, the other dances and gestures). `controller.toml`
loses the states, rules and buttons of the dropped modes; `bundle.json` lists
only what is shipped, with fresh sizes and SHA-256s; `manual.en.json` is
regenerated by `scripts/deploy.py::write_manual` from the controller's own
`pad_guide()`. Then `deploy.py --check-reference` replays the bundle's recorded
reference frames through the bundle's own controller.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import re
import shutil
import sys
import tempfile
import tomllib
import zipfile
from pathlib import Path

KEEP = ["locomotion", "claw_left", "gesture_bow", "gesture_hello", "gesture_salute", "dance_brazilian"]


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def trim_toml(text: str, dropped: set) -> str:
    lines = text.splitlines(keepends=True)
    out, chunk = [], []

    def flush():
        if not chunk:
            return
        header = chunk[0].strip()
        if header.startswith("[["):
            body = "".join(l for l in chunk if not l.lstrip().startswith("#"))
            kind = header.strip("[]")
            # parse just this table
            try:
                parsed = tomllib.loads(body.replace(header, "[x]", 1))["x"]
            except tomllib.TOMLDecodeError:
                parsed = {}
            if kind == "fsm.state" and parsed.get("name") in dropped:
                return
            if kind == "fsm.rule" and parsed.get("enter") in dropped:
                return
            if kind == "fsm.button" and parsed.get("name") in dropped:
                return
            new = []
            for l in chunk:
                m = re.match(r"^(from|leaves) = \[(.*)\]\s*$", l)
                if m:
                    items = [s.strip().strip('"') for s in m.group(2).split(",") if s.strip()]
                    items = [s for s in items if s not in dropped]
                    if not items:
                        # a binding that only reached dropped modes binds nothing now
                        return
                    l = f'{m.group(1)} = [{", ".join(chr(34) + s + chr(34) for s in items)}]\n'
                new.append(l)
            out.extend(new)
        else:
            out.extend(chunk)

    for l in lines:
        if l.startswith("[[") or (l.startswith("[") and not l.startswith("[ ")):
            flush()
            chunk = [l]
        else:
            chunk.append(l)
    flush()
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--jumper", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    src = a.jumper / "out/bundle_example/jumper"
    work = Path(tempfile.mkdtemp(prefix="cart-heist-app-")) / "cart_heist"
    shutil.copytree(src, work)
    manifest = json.loads((work / "bundle.json").read_text())
    dropped = set(manifest["modes"]) - set(KEEP)

    # files only the dropped modes use
    keep_files = set()
    for mode in KEEP:
        e = manifest["modes"][mode]
        keep_files |= {e["contract"], *e["models"].values()}
        if e.get("trajectory"):
            keep_files.add(e["trajectory"])
    for mode in dropped:
        e = manifest["modes"][mode]
        for f in {e["contract"], *e["models"].values(), e.get("trajectory")} - {None} - keep_files:
            (work / f).unlink(missing_ok=True)
    manifest["modes"] = {k: v for k, v in manifest["modes"].items() if k in KEEP}
    manifest["built_from"] = {k: v for k, v in manifest.get("built_from", {}).items() if k in KEEP}
    manifest["notes"] = [n for n in manifest.get("notes", []) if n.split(":")[0] not in dropped]
    manifest["notes"].append(
        "cart_heist: trimmed from the shipped jumper bundle (controller unchanged) to "
        + ", ".join(KEEP) + " for the King Crab Cart Heist sim. "
        "No policy or controller was rebuilt; files kept are byte-identical to the source bundle.")

    toml = trim_toml((work / "controller.toml").read_text(), dropped)
    toml = ("# King Crab Cart Heist: trimmed to " + ", ".join(KEEP) + " from the shipped jumper bundle.\n" + toml)
    (work / "controller.toml").write_text(toml)
    tomllib.loads(toml)  # must still parse

    # the Chinese manual would describe dropped modes; it is not regenerated here
    (work / "manual.zh.json").unlink(missing_ok=True)
    manifest["manuals"] = {"en": "manual.en.json"}
    (work / "README.md").write_text(
        "# cart_heist\n\nThe shipped Jumper bundle trimmed to the six modes the King Crab "
        "Cart Heist simulation uses: " + ", ".join(KEEP) + ".\n\n"
        "Controller builds (board, web, mjlab), policies, contracts, recordings and the reference "
        "frames are byte-identical to the source bundle; `controller.toml`, `bundle.json` and "
        "`manual.en.json` were regenerated for the smaller set of modes. See the source bundle's "
        "README for the host protocol.\n\n"
        "    python scripts/play.py --app cart_heist.app --scene black_friday_store.map\n"
        "    python scripts/deploy.py --check-reference <unzipped dir>\n")

    # write the manifest once so write_manual can read it, then regenerate the manual
    (work / "bundle.json").write_text(json.dumps(manifest, indent=2) + "\n")
    sys.path.insert(0, str(a.jumper / "scripts"))
    spec = importlib.util.spec_from_file_location("deploy_script", a.jumper / "scripts/deploy.py")
    deploy = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(deploy)
    ext = work / manifest["runtimes"]["mjlab"]["extensions"]["linux-x86_64"]["file"]
    fsm = deploy._load_for_reference(work, manifest, ext)
    if isinstance(fsm, str):
        raise SystemExit("controller refused the trimmed bundle: " + fsm)
    deploy.write_manual(work, fsm)

    files = {}
    for p in sorted(work.rglob("*")):
        rel = p.relative_to(work).as_posix()
        if p.is_file() and rel != "bundle.json":
            files[rel] = {"bytes": p.stat().st_size, "sha256": sha(p)}
    manifest["files"] = files
    (work / "bundle.json").write_text(json.dumps(manifest, indent=2) + "\n")

    out = a.out.resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(work.rglob("*")):
            if p.is_file():
                info = zipfile.ZipInfo(p.relative_to(work).as_posix(), date_time=(1980, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = (0o755 if p.stat().st_mode & 0o111 else 0o644) << 16
                z.writestr(info, p.read_bytes())
    print("wrote", out, f"{out.stat().st_size / 1e6:.1f} MB; modes:", ", ".join(KEEP),
          "; dropped:", ", ".join(sorted(dropped)))
    rc = deploy.check_reference(work)
    return rc or 0


if __name__ == "__main__":
    sys.exit(main())
